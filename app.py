# تحويل رسائل التطبيق إلى History خاص بـ Gemini
# ============================================================

def build_gemini_history(messages):
    """
    تحويل تاريخ المحادثة إلى التنسيق الذي تتطلبه
    google.generativeai.
    """

    history = []

    for message in messages:

        role = message.get("role")
        content = message.get("content")

        if not content:
            continue

        if role == "user":

            history.append(
                {
                    "role": "user",
                    "parts": [content],
                }
            )

        elif role == "assistant":

            history.append(
                {
                    "role": "model",
                    "parts": [content],
                }
            )

    return history


# ============================================================
# إنشاء جلسة المحادثة
