# قراءة مفتاح Gemini من Streamlit Secrets
# ============================================================

def get_gemini_api_key():
    """
    قراءة مفتاح Gemini من Streamlit Secrets.

    المفتاح المطلوب:

    GEMINI_API_KEY

    لا يتم وضع المفتاح داخل الكود.
    """

    try:
        api_key = st.secrets["GEMINI_API_KEY"]
    except Exception:
        return None

    if api_key is None:
        return None

    api_key = str(api_key).strip()

    if not api_key:
        return None

    return api_key


